def запрос(метод, **параметры):
    """Дёрнуть метод Bot API. Возвращает result или None."""
    данные = json.dumps(параметры).encode("utf-8")
    req = urllib.request.Request(
        API + метод, data=данные,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as ответ:
            тело = json.loads(ответ.read().decode("utf-8"))
            return тело.get("result")
    except urllib.error.HTTPError as e:
        текст = e.read().decode("utf-8", "replace")
        print("Телеграм вернул ошибку на", метод, ":", текст)
    except Exception as e:                                  # сеть моргнула
        print("Не дозвонился до Телеграма:", e)
    return None


def написать(кому, текст, кнопки=None, ответ_на=None):
    параметры = {
        "chat_id": кому,
        "text": текст,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    if кнопки:
        параметры["reply_markup"] = кнопки
    if ответ_на:
        параметры["reply_to_message_id"] = ответ_на
    return запрос("sendMessage", **параметры)


