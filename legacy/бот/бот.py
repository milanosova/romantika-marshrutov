def найти_человека(кого):
    """По @нику или по имени. Возвращает id или None.

    Сравниваем в питоне, а не в SQL: sqlite-шный lower() кириллицу не трогает.
    """
    кого = кого.strip().lstrip("@").lower()
    if not кого:
        return None
    with бд() as conn:
        все = conn.execute("SELECT id, ник, имя FROM люди").fetchall()

    for р in все:                                   # точное совпадение
        if (р["ник"] or "").lower() == кого or (р["имя"] or "").lower() == кого:
            return р["id"]

    похожие = [р["id"] for р in все if кого in (р["имя"] or "").lower()]
    return похожие[0] if len(похожие) == 1 else None


