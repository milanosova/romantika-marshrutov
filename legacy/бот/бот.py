def поставить_штамп(человек, номер, уровень):
    н = неделя_по_номеру(номер)
    название = н["title"] if н else "неделя " + str(номер)
    with бд() as conn:
        было = conn.execute(
            "SELECT уровень FROM штампы WHERE человек=? AND неделя=?",
            (человек, номер),
        ).fetchone()
        # максимум не понижаем до минимума
