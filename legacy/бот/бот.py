def обработать_сообщение(сообщ):
    чат = сообщ["chat"]["id"]
    от_кого = сообщ.get("from") or {}
    if от_кого.get("is_bot"):
        return
    записать_человека(от_кого)
    человек = от_кого["id"]
    текст = (сообщ.get("text") or сообщ.get("caption") or "").strip()

    # ── команды и кнопки
    если_админ = АДМИН and человек == АДМИН

    # ── Мила ответила реплаем на присланный отчёт → доставляем автору
    ответ_на = (сообщ.get("reply_to_message") or {}).get("message_id")
    if если_админ and ответ_на and текст:
        with бд() as conn:
            связь = conn.execute(
                "SELECT автор, неделя FROM связи WHERE сообщение=?", (ответ_на,)
            ).fetchone()
        if связь:
            дошло = написать(
                связь["автор"],
                "💬 <b>Мила ответила на твой отчёт:</b>\n\n" + escape(текст),
            )
            написать(чат, "Отправила ✅" if дошло else
                          "Не дошло — человек, видимо, заблокировал бота")
            return

    # ── бот о чём-то спросил и ждёт ответа следующим сообщением
    ждём = что_ждём(человек)
    кнопка = без_эмодзи(текст)   # «📋 Задание» → «задание», без эмодзи

    # нажатие кнопки — не ответ на вопрос бота: снимаем ожидание и идём дальше
    if текст and (текст.startswith("/") or это_кнопка(текст)):
        if ждём:
            не_ждать(человек)
            ждём = ""

    if ждём and текст and not текст.startswith("/") and not это_кнопка(текст):
        не_ждать(человек)

        if ждём == "слово":
            первое = not any(б["причина"] == "слово"
                             for б in бонусные_заморозки(человек))
            добавить_слово(человек, текст)
            хвост = ""
            if первое and дать_заморозку(человек, "слово"):
                хвост = ("\n\n❄️ И тебе +1 заморозка — это право пропустить "
                         "неделю так, чтобы цепочка не порвалась. "
                         "Смотри «📘 Паспорт».")
            написать(чат, "Записала в общий словарик 📖\n\n"
                          "К концу сезона соберём из них словарь — твоё слово "
                          "будет там с твоим именем." + хвост,
                     клавиатура(человек))
            if АДМИН and человек != АДМИН:
                написать(АДМИН, "📖 " + escape(как_зовут(человек))
                                + " добавил слово: " + escape(текст))
            return

        if ждём == "сообщение":
            написать(чат, "Передала ✅ Отвечу, как увижу.", клавиатура(человек))
            if АДМИН and человек != АДМИН:
                шапка = написать(
                    АДМИН,
                    "✉️ <b>Сообщение от " + escape(как_зовут(человек))
                    + "</b>\n\n" + escape(текст)
                    + "\n\n<i>Ответь реплаем — передам.</i>")
                if шапка and шапка.get("message_id"):
                    with бд() as conn:
                        conn.execute(
                            "INSERT OR REPLACE INTO связи VALUES (?,?,?)",
                            (шапка["message_id"], человек, 0))
            return

        if ждём.startswith("правка:") and если_админ:
            _, номер, поле = ждём.split(":")
            править_неделю(int(номер), поле, текст)
            н = неделя_по_номеру(int(номер))
            написать(чат, "Готово. Неделя " + номер + " теперь так:\n\n"
                     + текст_задания(н)
                     + "\n\n<i>Правка живёт в базе, не в файле — "
                       "обновление кода её не затрёт.</i>", панель())
            return

        if ждём == "факт":
            добавить_факт(текст, автор=None if если_админ else человек)
            если_админ or написать(
                чат, "Спасибо, записала ✅ Твой факт теперь в общем списке, "
                     "с твоим именем — и попадёт в журнал сезона.",
                клавиатура(человек))
            if если_админ:
                написать(чат, "Записала. Фактов за сезон: <b>"
                              + str(len(все_факты())) + "</b>",
                         кнопки_фактов(True))
            elif АДМИН:
                написать(АДМИН, "💡 " + escape(как_зовут(человек))
                                + " добавил факт: " + escape(текст))
            return

        if ждём.startswith("пожелание:") and если_админ:
            кому = int(ждём.split(":")[1])
            with бд() as conn:
                conn.execute(
                    "INSERT INTO пожелания VALUES (?,?,?) "
                    "ON CONFLICT(человек) DO UPDATE SET текст=excluded.текст",
                    (кому, текст,
                     сейчас_мск().isoformat(timespec="seconds")),
                )
            написать(чат, "Записала для " + escape(как_зовут(кому))
                          + ". Попадёт в его журнал в конце сезона.")
            return

    if текст.startswith("/start"):
        написать(чат, ПРИВЕТ, клавиатура(человек))
        return

    if (кнопка == "помощь" or текст.startswith("/help")
            or текст.startswith("/помощь")):
        написать(чат, ПОМОЩЬ, клавиатура(человек))
        if если_админ:
            написать(чат, ПАМЯТКА_АДМИНУ)
        return

    if текст.startswith("/whoami"):
        написать(чат, "Твой id: <code>" + str(человек) + "</code>\n"
                      "Положи его в файл <code>админ.txt</code>, "
                      "чтобы получить админские команды.")
        return

    if кнопка == "ещё":
        написать(чат, "Что открыть:", ЕЩЁ)
        return

    if кнопка == "задание" or текст.startswith("/task"):
        н = неделя_на()
        if н:
            написать(чат, текст_задания(н), кнопки_задания(н["num"]))
        else:
            написать(чат, "Сейчас неделя сезона не идёт. Ближайшее задание — "
                          "в понедельник.")
        return

    if кнопка == "сегодня" or текст.startswith("/today"):
        написать(чат, текст_дня())
        return

    if кнопка in ("паспорт", "мой паспорт") or текст.startswith("/passport"):
        написать(чат, паспорт(человек), {"inline_keyboard": [[
            {"text": "📔 Что будет в конце сезона",
             "callback_data": "что_в_конце"}
        ]]})
        return

    if (кнопка == "мой журнал" or текст.startswith("/журнал")
            or текст.startswith("/journal")):
        кого = человек
        # у кнопки в подписи есть пробел — её нельзя разбирать как команду
        по_кнопке = кнопка == "мой журнал"
        хвост = "" if по_кнопке else (
            текст.split(None, 1)[1].strip() if " " in текст else "")
        if если_админ and хвост:
            найден = найти_человека(хвост)
            if найден is None:
                написать(чат, "Не нашла такого. Список: /who")
                return
            кого = найден
        отправить_журнал(чат, кого)
        if кого == человек:
            написать(чат, "Так он выглядит сейчас. К 18 ноября здесь будет "
                          "весь сезон.")
        return

    if кнопка == "что узнали" or текст.startswith("/факты"):
        куски = [текст_фактов()]
        if все_факты():
            куски.append("\n<i>Пополняется после каждого поста. В конце "
                         "сезона всё это будет в твоём журнале.</i>")
        написать(чат, "\n".join(куски), кнопки_фактов(если_админ))
        return

    if кнопка == "написать миле":
        ждать(человек, "сообщение")
        написать(чат, "Пиши. Я прочитаю и отвечу — это не отчёт по заданию, "
                      "а обычное сообщение.\n\n"
                      "<i>Если сделала что-то, за что положена заморозка — "
                      "оставила комментарий, привела кого-то, пришла на "
                      "встречу — тоже напиши сюда. Я могла не заметить.</i>")
        return

    if кнопка == "мила" and если_админ:
        написать(чат, ПАНЕЛЬ_ТЕКСТ, панель())
        return

    if если_админ and текст.startswith("/пожелание"):
        хвост = текст.split(None, 1)[1].strip() if " " in текст else ""
        кому = None
        if ответ_на:
            with бд() as conn:
                связь = conn.execute(
                    "SELECT автор FROM связи WHERE сообщение=?", (ответ_на,)
                ).fetchone()
            if связь:
                кому = связь["автор"]
        if кому is None and хвост:
            части = хвост.split(None, 1)
            кому = найти_человека(части[0])
            хвост = части[1].strip() if len(части) > 1 else ""
        if кому is None or not хвост:
            написать(чат, "Так: <code>/пожелание @ksu текст</code> "
                          "или ответом на отчёт: <code>/пожелание текст</code>")
            return
        with бд() as conn:
            conn.execute(
                "INSERT INTO пожелания VALUES (?,?,?) "
                "ON CONFLICT(человек) DO UPDATE SET текст=excluded.текст",
                (кому, хвост, сейчас_мск().isoformat(timespec="seconds")),
            )
        написать(чат, "Записала для " + escape(как_зовут(кому))
                      + ". Попадёт в его журнал в конце сезона.")
        return

    if кнопка == "словарь" or текст.startswith("/words"):
        написать(чат, словарь_сезона(), кнопка_слова())
        return

    if если_админ and текст.startswith("/results"):
        части = текст.split()
        номер = int(части[1]) if len(части) > 1 and части[1].isdigit() else None
        написать(чат, сводка(номер))
        return

    if если_админ and текст.startswith("/core"):
        написать(чат, текст_ядра())
        return

    if если_админ and текст.startswith("/remind"):
        написать(чат, напомнить())
        return

    if если_админ and (текст.startswith("/badges")
                       or текст.startswith("/ачивки")):
        написать(чат, список_ачивок())
        return

    if если_админ and (текст.startswith("/ачивка")
                       or текст.startswith("/badge")):
        хвост = текст.split(None, 1)[1].strip() if " " in текст else ""
        кому = None
        if ответ_на:                       # выдаём в ответ на присланный отчёт
            with бд() as conn:
                связь = conn.execute(
                    "SELECT автор FROM связи WHERE сообщение=?", (ответ_на,)
                ).fetchone()
            if связь:
                кому = связь["автор"]
        if кому is None and хвост:         # иначе первое слово — ник или имя
            части = хвост.split(None, 1)
            кому = найти_человека(части[0])
            хвост = части[1].strip() if len(части) > 1 else ""

        if кому is None:
            написать(чат, "Не поняла, кому. Ответь этой командой на присланный "
                          "отчёт или укажи ник: <code>/ачивка @ksu повар</code>\n\n"
                          "Список: /badges")
            return
        if not хвост:
            написать(чат, "Не поняла, какую. Список: /badges")
            return

        код, подпись = выдать_ачивку(кому, хвост)
        имя = как_зовут(кому)
        if код is None:
            написать(чат, "У " + escape(имя) + " такая уже есть: " + подпись)
            return
        написать(кому,
                 "🏅 <b>Тебе ачивка: " + подпись + "</b>\n\n"
                 "Не за посещаемость, а за поступок. Она останется в паспорте "
                 "сезона и попадёт в итоговый журнал.")
        написать(чат, "Выдала " + подпись + " → " + escape(имя))
        return

    if если_админ and текст.startswith("/reminders"):
        было = вспомнить("напоминания", "вкл")
        стало = "выкл" if было == "вкл" else "вкл"
        запомнить("напоминания", стало)
        написать(
            чат,
            "Автонапоминания <b>" + стало + "</b>.\n\n"
            "Когда включены: <b>четверг 19:00</b> («впереди выходные») и "
            "<b>воскресенье 12:00</b> («сегодня до 18:00»).\n"
            "Уходят только тем, кто нажал «Берусь» или «Попробую» и ещё не "
            "прислал. Нажавшим «В этот раз мимо» — ничего.\n\n"
            "Повторить эту команду — переключить обратно.",
        )
        return

    if если_админ and текст.startswith("/who"):
        with бд() as conn:
            все = conn.execute(
                "SELECT id FROM люди ORDER BY пришёл"
            ).fetchall()
        строки = ["<b>В боте " + str(len(все)) + " человек</b>", ""]
        строки += ["· " + escape(как_зовут(р["id"])) for р in все]
        написать(чат, "\n".join(строки))
        return

    if текст.startswith("/"):
        написать(чат, "Такой команды нет. Жми кнопки внизу 👇",
                 клавиатура(человек))
        return

    # ── всё остальное считаем отчётом
    н = неделя_на()
    if not н:
        написать(чат, "Спасибо! Сейчас неделя сезона не идёт, "
                      "но я сохранил — покажу Миле.")
        return

    вид, файл = "text", None
    if "photo" in сообщ:
        вид, файл = "photo", сообщ["photo"][-1]["file_id"]
    elif "video" in сообщ:
        вид, файл = "video", сообщ["video"]["file_id"]
    elif "video_note" in сообщ:
        вид, файл = "video_note", сообщ["video_note"]["file_id"]
    elif "document" in сообщ:
        вид, файл = "document", сообщ["document"]["file_id"]

    if not текст and not файл:
        return

    уровень, ид_отчёта = принять_отчёт(человек, н["num"], вид, текст, файл)

    бонус = ""
    if уровень == "максимум" and not any(
            б["причина"] == "максимум" for б in бонусные_заморозки(человек)):
        if дать_заморозку(человек, "максимум"):
            бонус = ("\n\n❄️ И тебе +1 заморозка за первый максимум — "
                     "это право пропустить неделю так, чтобы цепочка "
                     "не порвалась.")

    if уровень == "максимум":
        ответ = ("⭐ Записала как <b>максимум</b> — штамп со звёздочкой "
                 "за неделю «" + escape(н["title"]) + "».")
        другой = "минимум"
    else:
        ответ = ("✅ Записала как <b>минимум</b> — штамп за неделю «"
                 + escape(н["title"]) + "».")
        другой = "максимум"

    написать(
        чат,
        ответ + бонус + "\n\nВ воскресенье покажу общие итоги.",
        {"inline_keyboard": [
            [{"text": "Это был " + другой,
              "callback_data": "уровень:" + str(н["num"]) + ":" + другой}],
            [{"text": "✉️ Это не отчёт, а сообщение Миле",
              "callback_data": "неотчёт:" + str(ид_отчёта)}],
        ]},
    )

    if АДМИН and человек != АДМИН:
        подпись = как_зовут(человек)
        шапка = написать(
            АДМИН,
            "📨 Отчёт за неделю " + str(н["num"]) + " от " + escape(подпись)
            + (": " + escape(текст[:300]) if текст else " (" + вид + ")")
            + "\n\n<i>Ответь на это сообщение — я передам ответ автору.</i>",
        )
        копия = None
        if файл:
            копия = запрос("copyMessage", chat_id=АДМИН, from_chat_id=чат,
                           message_id=сообщ["message_id"])
        # запоминаем, кому отвечать, если Мила ответит реплаем
        with бд() as conn:
            for м in (шапка, копия):
                if м and м.get("message_id"):
                    conn.execute(
                        "INSERT OR REPLACE INTO связи VALUES (?,?,?)",
                        (м["message_id"], человек, н["num"]),
                    )


def обработать_кнопку(вызов):
    данные = вызов.get("data", "")
    от_кого = вызов["from"]
    человек = от_кого["id"]
    записать_человека(от_кого)
    сообщ = вызов.get("message") or {}
    чат = (сообщ.get("chat") or {}).get("id")

    if данные.startswith(("берусь:", "попробую:", "мимо:")):
        выбор, номер = данные.split(":")
        номер = int(номер)
        with бд() as conn:
            conn.execute(
                "INSERT INTO берусь VALUES (?,?,?,?) "
                "ON CONFLICT(человек, неделя) DO UPDATE SET выбор=excluded.выбор",
                (человек, номер, выбор,
                 сейчас_мск().isoformat(timespec="seconds")),
            )
        подсказка = {
            "берусь": "Записала: берёшься 💪\n\nКак сделаешь — пришли сюда "
                      "текст или фото, и я поставлю штамп в паспорт.",
            "попробую": "Записала: попробуешь.\n\nДаже минимум на пять минут "
                        "считается — это полноценный штамп.",
            "мимо": "Хорошо, неделя может не задаться.\n\nНапоминаний "
                    "не пришлю. Реакция под постом — тоже участие.",
        }[выбор]
        запрос("answerCallbackQuery", callback_query_id=вызов["id"],
               text=подсказка, show_alert=True)
        if АДМИН and человек != АДМИН:
            написать(АДМИН, "👤 " + escape(как_зовут(человек)) + " — <b>"
                            + выбор + "</b> на неделе " + str(номер))
        return

    админ = АДМИН and человек == АДМИН
    ок = lambda подсказка="": запрос(
        "answerCallbackQuery", callback_query_id=вызов["id"], text=подсказка)

    # ─── панель Милы ───────────────────────────────────────────
    if данные == "факт_добавить":
        ок()
        ждать(человек, "факт")
        if чат:
            написать(чат, "Что записать? Пиши одним сообщением.\n\n"
                          "<i>Например: Ацтеки называли себя мешика — отсюда "
                          "«Мексика». Это попадёт в общий список и в журнал "
                          "сезона, с твоим именем.</i>")
        return

    if админ and (данные.startswith("п:") or данные.startswith("факт")
                  or данные.startswith("ач:") or данные.startswith("дать:")
                  or данные.startswith("пож:") or данные.startswith("удф:")
                  or данные.startswith("зам:") or данные.startswith("замд:")
                  or данные.startswith("пн:") or данные.startswith("пп:")):
        ок()

        if данные == "п:назад":
            написать(чат, ПАНЕЛЬ_ТЕКСТ, панель())
        elif данные == "п:привал":
            написать(чат, черновик_привала())
        elif данные == "п:сводка":
            написать(чат, сводка())
        elif данные == "п:ядро":
            написать(чат, текст_ядра())
        elif данные == "п:кто":
            with бд() as conn:
                все = conn.execute("SELECT id FROM люди ORDER BY пришёл").fetchall()
            строки = ["<b>В боте " + str(len(все)) + " человек</b>", ""]
            строки += ["· " + escape(как_зовут(р["id"])) for р in все]
            написать(чат, "\n".join(строки))
        elif данные == "п:напомнить":
            написать(чат, напомнить())
        elif данные == "п:автонап":
            стало = "выкл" if вспомнить("напоминания", "вкл") == "вкл" else "вкл"
            запомнить("напоминания", стало)
            написать(чат, "Автонапоминания <b>" + стало + "</b>. Когда включены — "
                          "четверг 19:00 и воскресенье 12:00, только тем, "
                          "кто взялся и не прислал.", панель())
        elif данные == "п:ачивка":
            написать(чат, "Кому выдаём?", люди_кнопками("ач"))
        elif данные == "п:правка":
            свободные = [н for н in недели()
                         if в_дату(н["end"]) >= сегодня_мск()]
            ряды = [[{"text": ("▶ " if в_дату(н["start"]) <= сегодня_мск()
                               else "🔒 ") + str(н["num"]) + " · " + н["title"],
                      "callback_data": "пн:" + str(н["num"])}]
                    for н in свободные[:12]]
            ряды.append([{"text": "‹ назад", "callback_data": "п:назад"}])
            написать(чат, "Какую неделю правим?\n\n<i>▶ — идёт сейчас, "
                          "🔒 — ещё закрыта. Прошедшие не показываю: люди их "
                          "уже прожили, задним числом не меняем.</i>",
                     {"inline_keyboard": ряды})

        elif данные.startswith("пн:"):
            номер = int(данные.split(":")[1])
            н = неделя_по_номеру(номер)
            строки = ["<b>Неделя " + str(номер) + " · " + escape(н["title"])
                      + "</b>", ""]
            for поле, подпись in ПОЛЯ_НЕДЕЛИ.items():
                значение = н.get(поле) or "—"
                строки.append("<b>" + подпись + ":</b> " + escape(значение[:160]))
            ряды = [[{"text": подпись,
                      "callback_data": "пп:" + str(номер) + ":" + поле}]
                    for поле, подпись in ПОЛЯ_НЕДЕЛИ.items()]
            ряды.append([{"text": "‹ назад", "callback_data": "п:правка"}])
            написать(чат, "\n".join(строки) + "\n\nЧто меняем?",
                     {"inline_keyboard": ряды})

        elif данные.startswith("пп:"):
            _, номер, поле = данные.split(":")
