    """Кто сдавал минимум N недель подряд. Главная цифра сезона."""
    with бд() as conn:
        люди = [
            р["человек"] for р in conn.execute(
                "SELECT DISTINCT человек FROM штампы"
            ).fetchall()
        ]
    свои = [(ч, подряд(ч)) for ч in люди]
    return sorted([п for п in свои if п[1] >= минимум], key=lambda п: -п[1])


