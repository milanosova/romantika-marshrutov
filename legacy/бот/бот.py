def склонение(н, одна, две, много):
    """1 неделя · 2 недели · 5 недель"""
    н = abs(н)
    if 11 <= н % 100 <= 14:
        return много
    return {1: одна, 2: две, 3: две, 4: две}.get(н % 10, много)


