def главный_цикл():
    завести_базу()
    я = запрос("getMe")
    if not я:
        print("Токен не подошёл. Проверь токен.txt")
        sys.exit(1)
    print("Бот @" + я.get("username", "?") + " запущен. Ctrl+C — остановить.")
    if not АДМИН:
        print("Админ не задан: напиши боту /whoami и положи свой id "
              "в файл админ.txt")

    смещение = int(вспомнить("смещение", 0))
    while True:
        try:
            авто_напоминания()
        except Exception as e:
            print("Автонапоминание не сработало:", e)

        обновления = запрос("getUpdates", offset=смещение, timeout=30,
                            allowed_updates=["message", "callback_query"])
        if обновления is None:
            time.sleep(3)
            continue
        for об in обновления:
            смещение = об["update_id"] + 1
            запомнить("смещение", смещение)
            try:
                if "message" in об:
                    обработать_сообщение(об["message"])
                elif "callback_query" in об:
                    обработать_кнопку(об["callback_query"])
            except Exception as e:
                print("Споткнулся на обновлении", об.get("update_id"), ":", e)


if __name__ == "__main__":
    try:
        главный_цикл()
    except KeyboardInterrupt:
        print("\nОстановлен.")
