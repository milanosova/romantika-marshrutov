def отменить_отчёт(ид):
    """Человек сказал, что это было сообщение, а не отчёт. Убираем след."""
    with бд() as conn:
        строка = conn.execute(
            "SELECT человек, неделя, текст FROM отчёты WHERE id=?", (ид,)
        ).fetchone()
        if not строка:
            return None
        conn.execute("DELETE FROM отчёты WHERE id=?", (ид,))
        осталось = conn.execute(
            "SELECT COUNT(*) c FROM отчёты WHERE человек=? AND неделя=?",
            (строка["человек"], строка["неделя"])).fetchone()["c"]
        if not осталось:                      # других отчётов за неделю нет
            conn.execute("DELETE FROM штампы WHERE человек=? AND неделя=?",
                         (строка["человек"], строка["неделя"]))
    return строка


