def юлианский_день(д):
    a = (14 - д.month) // 12
    y = д.year + 4800 - a
    m = д.month + 12 * a - 3
    return (д.day + (153 * m + 2) // 5 + 365 * y + y // 4 - y // 100
            + y // 400 - 32045)


def день_цолькина(д=None):
    д = д or сегодня_мск()
    x = юлианский_день(д) - КОРРЕЛЯЦИЯ
    число = ((x + 3) % 13) + 1
    имя, символ, смысл = ЗНАКИ_ЦОЛЬКИНА[(x + 19) % 20]
    return число, имя, символ, смысл


def вышедшие_слова(д=None):
    д = д or сегодня_мск()
    return [н for н in недели() if н["word"] and в_дату(н["start"]) <= д]


def слово_дня(д=None):
    """Слово текущей недели. Меняется по понедельникам, вместе с заданием."""
    н = неделя_на(д)
    if н and н["word"]:
        return н
    вышли = вышедшие_слова(д)          # неделя без слова — берём последнее
    return вышли[-1] if вышли else None


def слово_на_память(д=None):
    """«А помнишь?» — старое слово из словаря, каждый день другое.

    Появляется, только когда словарь набрал хотя бы три слова: раньше
    напоминать нечем, а крутить одно и то же по кругу — обман.
    """
    д = д or сегодня_мск()
    сейчас = слово_дня(д)
    старые = [н for н in вышедшие_слова(д)
              if not сейчас or н["num"] != сейчас["num"]]
    if len(старые) < 2:
        return None
    return старые[юлианский_день(д) % len(старые)]


def текст_дня():
    сегодня = сегодня_мск()
    ежедневное = СЕЗОН.get("daily") or {}
    строки = ["<b>🌤 " + сегодня.strftime("%d.%m") + "</b>", ""]

    if ежедневное.get("kind") == "tzolkin":
        число, имя, символ, смысл = день_цолькина(сегодня)
        строки += ["<b>" + str(число) + " " + имя + "</b> · " + символ,
                   "<i>" + смысл + "</i>", ""]

    сл = слово_дня(сегодня)
    if сл:
        строки += ([ЧЕРТА, "", "<b>Слово недели</b>"]
                   + строки_слова(сл) + [""])

    память = слово_на_память(сегодня)
    if память:
        строки += ["<b>А помнишь?</b>"] + строки_слова(память) + [""]

    строки += [ЧЕРТА, ""]
    if ежедневное.get("note"):
        строки += ["<i>" + escape(ежедневное["note"]) + "</i>", ""]
    строки.append("Задание недели — в «📋 Задание».")
    return "\n".join(строки)


