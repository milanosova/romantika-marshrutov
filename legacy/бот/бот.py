            _, кому, причина = данные.split(":")
            кому = int(кому)
            if дать_заморозку(кому, причина):
                написать(кому, "❄️ <b>Тебе +1 заморозка</b> — "
                               + ПРИЧИНЫ_ЗАМОРОЗОК[причина] + ".\n\n"
                               "Это право пропустить неделю так, чтобы цепочка "
                               "не порвалась. Смотри «📘 Паспорт».")
