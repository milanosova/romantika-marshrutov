#!/bin/bash
# Публикация поста с кнопкой в канал @romantika_marshrutov
# Токен вводится с клавиатуры и нигде не сохраняется.
set -euo pipefail

printf "Вставьте токен бота (BotFather → /token → @romantika_marshrutov_bot), ввод скрыт: "
read -r -s TOKEN
echo

TEXT='Что бы вы выбрали: вам назвали ваше призвание при рождении и вопрос закрылся — или искать самому и иметь право передумать?

У майя день рождения назначал предназначение

Ребёнка приносили к жрецу, тот смотрел, какой выпал день — знак и число вместе — и говорил, к чему этот человек предназначен. Иногда по дню давали и имя.

Думаю, что в этом есть утешение и ловушка одновременно. Человек, которому сказали, кем ему быть, не мучается выбором — но и не выбирает.
Сделала календарь, где можно посмотреть свой день и своё предназначение — жмите кнопку под постом 👇

Предупреждение ‼️
Сами дни и их символы настоящие, а вот расшифровку предназначений дописали уже в наше время, поэтому это в качестве развлекательного формата)

Так что выбрали бы? И напишите, какой день выпал

#страна_сезона #мексика #профориентация'

BUTTONS='{"inline_keyboard":[[{"text":"☀️ Узнать свой день","url":"https://t.me/romantika_marshrutov_bot/calendar"}]]}'

echo "Отправляю пост в @romantika_marshrutov…"
RESP=$(curl -s -X POST "https://api.telegram.org/bot${TOKEN}/sendMessage" \
  --data-urlencode "chat_id=@romantika_marshrutov" \
  --data-urlencode "text=${TEXT}" \
  --data-urlencode "reply_markup=${BUTTONS}")

if echo "$RESP" | grep -q '"ok":true'; then
  echo "✅ Опубликовано! Проверьте канал."
else
  echo "❌ Не получилось. Ответ Телеграма:"
  echo "$RESP"
fi
